/**
 * Builds the avatar stage: stage/main.ts (with three.js) bundled into one minified module,
 * and the 3D model copied next to it. Both get a content hash in their name so /stage/*
 * can be cached forever (see public/_headers), and lib/stage-assets.ts is generated with
 * the two URLs for the page to reference. Runs before `next build` and `next dev`.
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'public', 'stage');
const hash = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 8);

const result = await build({
  entryPoints: [join(root, 'stage', 'main.ts')],
  bundle: true,
  minify: true,
  format: 'esm',
  target: 'es2020',
  legalComments: 'none',
  write: false,
});
const js = result.outputFiles[0].contents;
const model = await readFile(join(root, 'assets', 'avatar', 'oscar-v2.glb'));

await mkdir(outDir, { recursive: true });
for (const f of await readdir(outDir)) await rm(join(outDir, f));
const script = `stage.${hash(js)}.js`;
const modelName = `oscar-v2.${hash(model)}.glb`;
await writeFile(join(outDir, script), js);
await writeFile(join(outDir, modelName), model);

await writeFile(
  join(root, 'lib', 'stage-assets.ts'),
  `// Generated by scripts/build-stage.mjs. Do not edit by hand.\nexport const stageAssets = {\n  script: '/stage/${script}',\n  model: '/stage/${modelName}',\n} as const;\n`,
);
const kb = (n) => `${(n / 1024).toFixed(0)} kB`;
console.log(`build-stage: ${script} (${kb(js.length)}), ${modelName} (${kb(model.length)})`);
